const FARE_MATRIX = {
    "Ampang Park-Cyberjaya Utara": 4.80,
    "Ampang Park-Cyberjaya City Centre": 5.20,
    "Ampang Park-KLCC": 1.60,
    "Ampang Park-Bukit Bintang": 2.20,
    "Hang Tuah-Cyberjaya Utara": 4.50,
    "Hang Tuah-Cyberjaya City Centre": 4.90,
    "Hang Tuah-KLCC": 2.10,
    "Hang Tuah-Bukit Bintang": 1.40,
    "KL Sentral-Cyberjaya Utara": 4.20,
    "KL Sentral-Cyberjaya City Centre": 4.60,
    "KL Sentral-KLCC": 2.40,
    "KL Sentral-Bukit Bintang": 2.00,
    "TRX-Cyberjaya Utara": 4.00,
    "TRX-Cyberjaya City Centre": 4.40,
    "TRX-KLCC": 1.90,
    "TRX-Bukit Bintang": 1.50
};

function getDiscountMultiplier(category) {
    const cat = String(category || "").toLowerCase();
    if (cat.includes("student")) return 0.5;
    if (cat.includes("oku") || cat.includes("senior")) return 0.5;
    return 1.0;
}

function openGateTapModal() {
    const card = getActiveCard();
    if (!card) return showToast("Please log in first.", "error");
    if (card.isBlocked) return showToast("This card is blocked.", "error");
    
    updateFarePreview();
    $("gateTapModal").style.display = "flex";
}

function updateFarePreview() {
    const card = getActiveCard();
    if (!card) return;

    const orig = $("tapOrigin").value;
    const dest = $("tapDestination").value;
    const routeKey = `${orig}-${dest}`;
    const baseFare = FARE_MATRIX[routeKey] || 3.50;
    
    const multiplier = getDiscountMultiplier(card.cardCategory);
    const finalFare = round2(baseFare * multiplier);
    
    $("tapStandardFare").innerText = money(baseFare);
    $("tapFinalFare").innerText = money(finalFare);
    $("tapConcessionRate").innerText = multiplier === 0.5 ? "50% Concession Off" : "Standard Rate";
}

document.addEventListener("change", e => {
    if (e.target.id === "tapOrigin" || e.target.id === "tapDestination") {
        updateFarePreview();
    }
});

function submitGateTap() {
    const cards = getAllCards();
    const card = cards.find(c => c.cardNumber === getActiveCardNumber());
    if (!card || card.isBlocked) return showToast("Card is inactive or blocked.", "error");

    const orig = $("tapOrigin").value;
    const dest = $("tapDestination").value;
    const baseFare = FARE_MATRIX[`${orig}-${dest}`] || 3.50;
    const finalFare = round2(baseFare * getDiscountMultiplier(card.cardCategory));

    if (card.balance < finalFare) {
        return showToast(`Insufficient balance! Fare: ${money(finalFare)}, Balance: ${money(card.balance)}`, "error");
    }

    card.balance = round2(card.balance - finalFare);
    addTx(card, "Fare", -finalFare, `Gate Tap: ${orig} ➔ ${dest}`);
    saveAllCards(cards);
    addAuditLog(`Gate Tap -${money(finalFare)} on card ${card.cardNumber} (${orig} to ${dest})`);

    closeModal("gateTapModal");
    loadActiveCardData();
    showToast(`Gate Opened! Deducted ${money(finalFare)}.`, "success");
    celebrate();
}

