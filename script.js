function downloadPdfReceipt() {
    const card = getActiveCard();
    if (!card) return showToast("Please log in first.", "error");
    const jsPDF = window.jspdf && window.jspdf.jsPDF;
    if (!jsPDF) return showToast("PDF library is still loading. Try again in a moment.", "error");

    try {
        const doc = new jsPDF();
        doc.setFont("helvetica", "bold"); doc.setFontSize(18); doc.setTextColor(15, 23, 42);
        doc.text("TRANSIT HUB MALAYSIA", 20, 20);
        doc.setFontSize(10); doc.setTextColor(100, 116, 139);
        doc.text("Official Transaction & Account Statement", 20, 26);
        doc.setLineWidth(0.5); doc.setDrawColor(200, 200, 200); doc.line(20, 32, 190, 32);

        doc.setFillColor(241, 245, 249); doc.roundedRect(20, 38, 170, 30, 3, 3, "F");
        doc.setFont("helvetica", "bold"); doc.setFontSize(11); doc.setTextColor(15, 23, 42);
        doc.text("Cardholder Profile", 26, 46);
        doc.setFont("helvetica", "normal"); doc.setFontSize(9);
        doc.text(`Card Number: ${card.cardNumber}`, 26, 54);
        doc.text(`Holder Name: ${card.holderName}`, 110, 54);
        doc.text(`Phone: ${card.phone}`, 26, 61);
        doc.text(`Category: ${card.cardCategory}`, 110, 61);

        doc.setFillColor(224, 242, 254); doc.roundedRect(20, 73, 170, 16, 3, 3, "F");
        doc.setFont("helvetica", "bold"); doc.setFontSize(10); doc.setTextColor(2, 132, 199);
        doc.text(`Available Balance: ${money(card.balance)}`, 26, 83);

        doc.setFontSize(12); doc.setTextColor(15, 23, 42);
        doc.text("Transaction History Log", 20, 100);

        let y = 110;
        doc.setFont("helvetica", "normal"); doc.setFontSize(9);
        if (!card.transactions.length) doc.text("No transactions recorded yet.", 20, y);

        card.transactions.forEach((tx, i) => {
            const lines = doc.splitTextToSize(String(tx.desc), 75);
            const h = Math.max(8, lines.length * 5 + 3);
            if (y + h > 275) { doc.addPage(); y = 20; }
            if (i % 2 === 0) { doc.setFillColor(248, 250, 252); doc.rect(20, y - 5, 170, h, "F"); }
            doc.setTextColor(100, 116, 139); doc.text(fmtDate(tx.date), 22, y);
            doc.setTextColor(30, 41, 59); doc.text(lines, 75, y);
            const amt = Number(tx.amount) || 0;
            if (amt) doc.text((amt > 0 ? "+" : "-") + money(Math.abs(amt)), 188, y, { align: "right" });
            y += h;
        });

        doc.setFontSize(8); doc.setTextColor(150, 150, 150);
        doc.text("This is a computer-generated statement from Transit Hub Pro. No signature required.", 20, 288);
        doc.save(`Transit_Statement_${card.cardNumber}.pdf`);
    } catch (e) {
        console.error(e);
        showToast("Could not generate the PDF statement.", "error");
    }
}

