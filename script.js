function downloadSingleReceiptPdf() {
    const card = getActiveCard();
    if (!card || !activeReceiptTx) return;
    const jsPDF = window.jspdf && window.jspdf.jsPDF;
    if (!jsPDF) return showToast("PDF engine loading...", "error");

    const doc = new jsPDF({ unit: "mm", format: [80, 120] });
    const tx = activeReceiptTx;

    doc.setFont("helvetica", "bold"); doc.setFontSize(12);
    doc.text("TRANSIT HUB MALAYSIA", 40, 12, { align: "center" });
    doc.setFontSize(8); doc.setFont("helvetica", "normal");
    doc.text("Official Transaction Receipt", 40, 16, { align: "center" });
    doc.line(8, 19, 72, 19);

    doc.text(`Card No: ${card.cardNumber}`, 10, 26);
    doc.text(`Holder: ${card.holderName}`, 10, 32);
    doc.text(`Category: ${card.cardCategory}`, 10, 38);
    doc.text(`Date: ${fmtDate(tx.date)}`, 10, 44);
    doc.text(`Type: ${tx.type}`, 10, 50);

    const descLines = doc.splitTextToSize(`Details: ${tx.desc}`, 60);
    doc.text(descLines, 10, 56);

    doc.line(8, 70, 72, 70);
    doc.setFont("helvetica", "bold"); doc.setFontSize(11);
    doc.text(`Amount: ${(tx.amount >= 0 ? "+" : "-") + money(Math.abs(tx.amount))}`, 10, 78);
    doc.setFontSize(9);
    doc.text(`Balance: ${money(card.balance)}`, 10, 84);

    doc.setFontSize(7); doc.setFont("helvetica", "normal");
    doc.text("Thank you for commuting with Transit Hub!", 40, 105, { align: "center" });

    doc.save(`Receipt_${card.cardNumber}_${Date.now()}.pdf`);
}